package io.cmdb.collector.syncrun.domain;

import jakarta.persistence.Column;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import org.jmolecules.ddd.annotation.AggregateRoot;
import org.jmolecules.ddd.annotation.Identity;
import tools.jackson.databind.JsonNode;

/**
 * One sync (one row of integration_sync_runs), used by cmdb-service to judge the data freshness of
 * each source.
 *
 * <p>Lifecycle: {@link #start} → RUNNING → {@link #finish} → SUCCESS / PARTIAL / FAILED; it can
 * finish only once.
 */
@AggregateRoot
@Table(name = "integration_sync_runs")
public class SyncRun {

  // id is generated by the database IDENTITY (the schema is shared with cmdb-service). The field is
  // not annotated with jMolecules @Identity:
  // jmolecules-jpa would turn it into @EmbeddedId, which requires the id to be an Identifier value
  // object created by the domain first and cannot be database-generated.
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  private Long id;

  private String provider;

  @Enumerated(EnumType.STRING)
  private SyncType syncType;

  private Instant startedAt;
  private Instant finishedAt;

  @Enumerated(EnumType.STRING)
  private SyncStatus status;

  private int recordsProcessed;

  @Column(columnDefinition = "text")
  private String errorMessage;

  @JdbcTypeCode(SqlTypes.JSON)
  private JsonNode cursorState;

  protected SyncRun() {}

  private SyncRun(String provider, SyncType syncType, Instant startedAt) {
    this.provider = provider;
    this.syncType = syncType;
    this.startedAt = startedAt;
    this.status = SyncStatus.RUNNING;
  }

  public static SyncRun start(String provider, SyncType type, Instant now) {
    if (provider == null || provider.isBlank()) {
      throw new IllegalArgumentException("provider is required");
    }
    return new SyncRun(provider, type, now);
  }

  public void finish(SyncStatus result, int records, String error, JsonNode cursor, Instant now) {
    if (status != SyncStatus.RUNNING) {
      throw new IllegalStateException("sync run already finished: " + status);
    }
    if (result == SyncStatus.RUNNING) {
      throw new IllegalArgumentException("a finished run cannot be RUNNING");
    }
    this.status = result;
    this.recordsProcessed = records;
    this.errorMessage = error;
    this.cursorState = cursor;
    this.finishedAt = now;
  }

  /**
   * jMolecules' DDD rules require an identity declaration; put on the method, not the field,
   * because @Identity on a field is converted to @EmbeddedId.
   */
  @Identity
  public Long id() {
    return id;
  }

  public String provider() {
    return provider;
  }

  public SyncType type() {
    return syncType;
  }

  public Instant startedAt() {
    return startedAt;
  }

  public Instant finishedAt() {
    return finishedAt;
  }

  public SyncStatus status() {
    return status;
  }

  public int records() {
    return recordsProcessed;
  }

  public String error() {
    return errorMessage;
  }

  public JsonNode cursor() {
    return cursorState;
  }
}
