package io.cmdb.collector.rawevent.domain;

import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import org.jmolecules.ddd.annotation.AggregateRoot;
import org.jmolecules.ddd.annotation.Identity;
import tools.jackson.databind.JsonNode;

/**
 * One event written to integration_raw_events (the Collector → Processor contract, see PLAN.md
 * 3.1).
 *
 * <p>The Collector writes only these columns; process_status (default PENDING), attempt_count,
 * received_at and so on are database defaults and the Processor's responsibility, so they are not
 * mapped here.
 */
@AggregateRoot
@Table(name = "integration_raw_events")
public class RawEvent {

  // id is generated by the database IDENTITY (the schema is shared with cmdb-service). The field is
  // not annotated with jMolecules @Identity:
  // jmolecules-jpa would turn it into @EmbeddedId, which requires the id to be an Identifier value
  // object created by the domain first and cannot be database-generated.
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  private Long id;

  private String provider;
  private String eventType;
  private String externalEventId;
  private String orderingKey;

  @JdbcTypeCode(SqlTypes.JSON)
  private JsonNode payload;

  protected RawEvent() {}

  public RawEvent(
      String provider,
      String eventType,
      String externalEventId,
      String orderingKey,
      JsonNode payload) {
    this.provider = require(provider, "provider", 30);
    this.eventType = require(eventType, "eventType", 100);
    this.externalEventId = require(externalEventId, "externalEventId", 200);
    if (orderingKey != null && orderingKey.length() > 300) {
      throw new IllegalArgumentException("orderingKey exceeds 300 chars");
    }
    this.orderingKey = orderingKey;
    if (payload == null || payload.isMissingNode() || payload.isNull()) {
      throw new IllegalArgumentException("payload is required");
    }
    this.payload = payload;
  }

  /**
   * jMolecules' DDD rules require an identity declaration; put on the method, not the field,
   * because @Identity on a field is converted to @EmbeddedId.
   */
  @Identity
  public Long id() {
    return id;
  }

  public String provider() {
    return provider;
  }

  public String eventType() {
    return eventType;
  }

  public String externalEventId() {
    return externalEventId;
  }

  public String orderingKey() {
    return orderingKey;
  }

  public JsonNode payload() {
    return payload;
  }

  /**
   * Creates a new event with the same identity after redaction (the original object is not
   * modified).
   */
  public RawEvent withPayload(JsonNode newPayload) {
    return new RawEvent(provider, eventType, externalEventId, orderingKey, newPayload);
  }

  private static String require(String value, String name, int max) {
    if (value == null || value.isBlank()) {
      throw new IllegalArgumentException(name + " is required");
    }
    if (value.length() > max) {
      throw new IllegalArgumentException(name + " exceeds " + max + " chars: " + value);
    }
    return value;
  }
}
